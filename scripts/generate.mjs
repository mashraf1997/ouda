// Generates the bundle compose files from scripts/apps.json.
// Run: node scripts/generate.mjs
// Each file must work when only that file is fetched (Hostinger's deploy button
// downloads the compose file alone), so the Caddy config and the start page are inline.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const cfg = JSON.parse(fs.readFileSync(path.join(root, 'scripts/apps.json'), 'utf8'));
const byId = Object.fromEntries(cfg.apps.map((a) => [a.id, a]));

// Compose interpolates "$", so every literal dollar sign is doubled.
const dollar = (s) => s.replace(/\$/g, '$$$$');
const indent = (s, n) => s.split('\n').map((l) => (l ? ' '.repeat(n) + l : l)).join('\n');

function startPage(apps, title, demo) {
  const items = apps.map((a) => ({ id: a.id, sub: a.sub, port: a.port, icon: a.icon, en: a.en, ar: a.ar }));
  return `<!DOCTYPE html>
<html lang="ar" dir="rtl"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>${title}</title>
<style>
:root{--bg:#F6F5F2;--card:#fff;--ink:#1B1A17;--muted:#6B6760;--line:#E4E1DA;--c:#0F766E;color-scheme:light}
@media (prefers-color-scheme:dark){:root{--bg:#141412;--card:#1D1C19;--ink:#ECEAE4;--muted:#A19D94;--line:#32302B;--c:#2DD4BF;color-scheme:dark}}
*{box-sizing:border-box}body{margin:0;background:var(--bg);color:var(--ink);font:16px/1.6 "Segoe UI","Noto Sans Arabic",Tahoma,system-ui,sans-serif;padding:32px 16px}
main{max-width:920px;margin:0 auto;display:grid;gap:20px}h1{margin:0;font-size:1.8rem}p{margin:0;color:var(--muted)}
.grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(250px,1fr));gap:12px}
a.app{display:grid;grid-template-columns:auto 1fr;gap:4px 12px;align-items:center;background:var(--card);border:1px solid var(--line);border-radius:14px;padding:14px;text-decoration:none;color:inherit}
a.app:hover{border-color:var(--c)}a.app span{font-size:1.8rem;grid-row:span 2}a.app b{text-transform:capitalize}a.app small{color:var(--muted)}
.note{font-size:.9rem}code{font-size:.85rem}
</style></head><body><main>
<h1>عُدّة · Ouda</h1>
${demo ? '<p><b>ديمو لايف:</b> كل أداة فيها بيانات تجريبية وكلمة السر مكتوبة في صفحة الدخول، والبيانات بترجع زي ما كانت كل ساعة. <b>Live demo:</b> every tool has sample data, the password is shown on its sign-in page, and everything resets every hour.</p>' : '<p>افتح كل أداة واعمل كلمة السر بتاعتها. Open each tool and create its password.</p>'}
<div class="grid" id="apps"></div>
<p class="note">لو عندك دومين، حط <code>DOMAIN</code> في إعدادات الحاوية، وكل أداة هتشتغل على subdomain بشهادة HTTPS تلقائي. With a domain, set <code>DOMAIN</code> and every tool gets its own HTTPS subdomain.</p>
</main>
<script>
var APPS = ${JSON.stringify(items)};
var h = location.hostname;
var named = !/^[0-9.]+$/.test(h) && h.indexOf(':') < 0 && h !== 'localhost';
document.getElementById('apps').innerHTML = APPS.map(function (a) {
  var url = named ? 'https://' + a.sub + '.' + h + '/' : 'http://' + h + ':' + a.port + '/';
  return '<a class="app" href="' + url + '"><span>' + a.icon + '</span><b>' + a.id + '</b><small>' + a.ar + '<br>' + a.en + '</small></a>';
}).join('');
</script></body></html>`;
}

function caddyScript(apps, demo) {
  const portBlocks = apps.map((a) => `:${a.port} {\n\treverse_proxy ${a.id}:3000\n}`).join('\n');
  const domainBlocks = apps.map((a) => `${a.sub}.{$DOMAIN} {\n\treverse_proxy ${a.id}:3000\n}`).join('\n');
  return `mkdir -p /srv
cat > /srv/index.html <<'HTML'
${startPage(apps, demo ? 'Ouda demo' : 'Ouda', demo)}
HTML
if [ -n "$ACME_EMAIL" ]; then printf '{\n\temail %s\n}\n' "$ACME_EMAIL" > /etc/caddy/Caddyfile; else : > /etc/caddy/Caddyfile; fi
cat >> /etc/caddy/Caddyfile <<'CADDY'
:80 {
\troot * /srv
\tfile_server
}
${portBlocks}
CADDY
if [ -n "$DOMAIN" ]; then
cat >> /etc/caddy/Caddyfile <<'CADDY'
{$DOMAIN} {
\troot * /srv
\tfile_server
}
${domainBlocks}
CADDY
fi
exec caddy run --config /etc/caddy/Caddyfile --adapter caddyfile`;
}

function compose(file, pack) {
  const apps = pack.apps.map((id) => byId[id]);
  const ports = ['"80:80"', '"443:443"', '"443:443/udp"', ...apps.map((a) => `"${a.port}:${a.port}"`)];
  let y = `# Ouda (${pack.en}) — generated by scripts/generate.mjs, do not edit by hand.${pack.demo ? '\n# DEMO: every tool runs with sample data that resets every hour. Do not use it for real customers.' : ''}
# One-click deploy on a Hostinger VPS (Docker Manager), or: docker compose -f ${file} up -d
#
# Without a domain: open http://YOUR-SERVER-IP for the start page; each tool has its own port.
# With a domain:    point *.example.com and example.com at the server, set DOMAIN=example.com,
#                   and every tool gets https://<name>.example.com with automatic certificates.
#
# Tools: ${apps.map((a) => `${a.id} (${a.sub}., :${a.port})`).join(', ')}
services:
  caddy:
    image: caddy:2-alpine
    restart: unless-stopped
    depends_on:
${apps.map((a) => `      - ${a.id}`).join('\n')}
    environment:
      - DOMAIN=\${DOMAIN:-}
      - ACME_EMAIL=\${ACME_EMAIL:-}
    ports:
${ports.map((p) => `      - ${p}`).join('\n')}
    entrypoint: ["/bin/sh", "-c"]
    command:
      - |
${indent(dollar(caddyScript(apps, pack.demo)), 8)}
    volumes:
      - caddy-data:/data
      - caddy-config:/config
`;
  for (const a of apps) {
    const env = pack.demo
      ? ['NODE_ENV=production', 'DEMO_MODE=true', 'DEMO_LANG=${DEMO_LANG:-ar}', 'DEMO_RESET_MINUTES=${DEMO_RESET_MINUTES:-60}', ...a.extraEnv.filter((e) => e !== 'ANTHROPIC_API_KEY').map((e) => `${e}=\${${e}:-}`)]
      : ['NODE_ENV=production', `${a.setupVar}=\${${a.setupVar}:-}`, 'DEMO_MODE=${DEMO_MODE:-false}', ...a.extraEnv.map((e) => `${e}=\${${e}:-}`)];
    y += `
  ${a.id}:
    image: ghcr.io/mashraf1997/${a.id}:latest
    restart: unless-stopped
    environment:
${env.map((e) => `      - ${e}`).join('\n')}
    volumes:
      - ${a.id}-data:/data
    expose:
      - "3000"
`;
  }
  y += `
volumes:
  caddy-data:
  caddy-config:
${apps.map((a) => `  ${a.id}-data:`).join('\n')}
`;
  return y;
}

for (const [file, pack] of Object.entries(cfg.packs)) {
  fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true });
  fs.writeFileSync(path.join(root, file), compose(file, pack));
  console.log('wrote', file);
}
